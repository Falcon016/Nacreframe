/** Session and swarm ids are generated by us (base36 + hex). Anything else could be a path. */
const ID = /^[a-z0-9]{8,32}$/;

export class HttpError extends Error {
  constructor(
    readonly status: number,
    message: string,
  ) {
    super(message);
  }
}

interface Client {
  res: ServerResponse;
  lastItemId: number;
  first: boolean;
}

export interface CreateSessionBody {
  cwd?: unknown;
  model?: unknown;
  approval?: unknown;
  sandbox?: unknown;
  resume?: unknown;
  swarmResume?: unknown;
}

export interface WebState {
  type: 'state';
  reset: boolean;
  version: string;
  session: {
    id: string;
    cwd: string;
    model: string | null;
    contextWindow: number;
    contextSource: string;
    /** Compaction trigger and hard ceiling, in tokens (0 = unknown). */
    target: number;
    hard: number;
    mode: ApprovalMode;
    sandbox: SandboxMode;
    sandboxDescription: string;
    running: boolean;
    swarm: { active: boolean; id?: string; names: string[] };
  };
  items: Item[];
  live: LiveAgent[];
  browser: UiSnapshot['browser'];
  tokens: UiSnapshot['tokens'];
  contextTokens: number;
  queued: number;
  compacting?: { pct: number };
  status?: string;
  todos: { content: string; status: string }[];
  approval?: ApprovalRequest & { id: number; pending: number };
  question?: { id: number; agent: string; question: string; options?: string[] };
  warnings: string[];
}

/** One live agent session on the server: a Runtime, its UI state, and the browsers watching it. */
export class WebSession {
  readonly id = newId('s_');
  readonly store = new UiStore();
  readonly clients = new Set<Client>();
  private seq = 0;
  private approval: { id: number; req: ApprovalRequest; resolve(r: ApprovalResponse): void } | undefined;
  private question: { id: number; agent: string; q: Question; resolve(a: string): void } | undefined;
  private timer: NodeJS.Timeout | undefined;
  readonly createdAt = Date.now();
  disposed = false;

  private constructor(readonly runtime: Runtime) {}

  static async create(
    body: CreateSessionBody,
    env: NodeJS.ProcessEnv,
    opts: { cwd: string; headless: boolean },
  ) {
    for (const k of ['resume', 'swarmResume'] as const) {
      const v = body[k];
      if (v !== undefined && v !== '' && !(typeof v === 'string' && ID.test(v)))
        throw new HttpError(400, `Invalid ${k} id`);
    }
    const overrides: Record<string, unknown> = {};
    if (typeof body.model === 'string' && body.model) overrides.model = body.model;
    if (typeof body.approval === 'string') overrides.approval = { mode: body.approval };
    if (typeof body.sandbox === 'string') overrides.sandbox = { mode: body.sandbox };
    if (opts.headless) overrides.browser = { headless: true };
    const runtime = await Runtime.create({
      cwd: opts.cwd,
      env,
      overrides,
      ...(typeof body.resume === 'string' && body.resume ? { resume: body.resume } : {}),
    });
    const s = new WebSession(runtime);
    s.wire();
    if (typeof body.resume === 'string' && body.resume) replayInto(s.store, runtime.agent.session.messages());
    for (const w of runtime.warnings) s.store.notice(w, 'warn');
    if (typeof body.swarmResume === 'string' && body.swarmResume) await s.swarm('resume', body.swarmResume);
    return s;
  }

  private wire(): void {
    const rt = this.runtime;
    this.store.attachAgent(rt.agent, 'main');
    if (rt.browser) this.store.attachBrowser(rt.browser.events);
    this.store.subscribe(() => this.push());
    for (const e of ['mode', 'sandbox', 'todos', 'model'] as const) rt.events.on(e, () => this.push(true));
    rt.broker.approvalHandler = (req, signal) =>
      new Promise<ApprovalResponse>((resolveApproval) => {
        const id = ++this.seq;
        const done = (r: ApprovalResponse) => {
          if (this.approval?.id === id) this.approval = undefined;
          this.push(true);
          resolveApproval(r);
        };
        signal.addEventListener('abort', () => done({ allow: false }), { once: true });
        this.approval = { id, req, resolve: done };
        this.push(true);
      });
    rt.broker.questionHandler = (agent, q) =>
      new Promise<string>((resolveAnswer) => {
        const id = ++this.seq;
        this.question = {
          id,
          agent,
          q,
          resolve: (a) => {
            if (this.question?.id === id) this.question = undefined;
            this.push(true);
            resolveAnswer(a);
          },
        };
        this.push(true);
      });
  }

  // ---- state → clients ------------------------------------------------------------------------------

  private build(c: Client): WebState {
    const rt = this.runtime;
    const snap = this.store.getSnapshot();
    const lim = rt.agent.limits();
    const items = snap.items.filter((i) => i.id > c.lastItemId);
    if (items.length) c.lastItemId = items[items.length - 1]!.id;
    const swarm = rt.swarm;
    const m = rt.agent.model;
    return {
      type: 'state',
      reset: c.first,
      version: VERSION,
      session: {
        id: this.id,
        cwd: rt.cwd,
        model: rt.modelSpec ?? null,
        contextWindow: m.contextWindow,
        contextSource: m.contextSource,
        target: Number.isFinite(lim.target) ? lim.target : 0,
        hard: Number.isFinite(lim.hard) ? lim.hard : 0,
        mode: rt.policy.mode,
        sandbox: rt.sandbox.mode,
        sandboxDescription: rt.sandbox.describe(),
        running: rt.agent.isRunning || !!swarm?.roster().some((t) => t.running),
        swarm: { active: !!swarm, ...(swarm?.id ? { id: swarm.id } : {}), names: swarm?.names ?? [] },
      },
      items,
      live: snap.live,
      browser: snap.browser,
      tokens: snap.tokens,
      contextTokens: snap.contextTokens,
      queued: snap.queued,
      ...(snap.compacting ? { compacting: snap.compacting } : {}),
      ...(snap.status ? { status: snap.status } : {}),
      todos: rt.todos,
      ...(this.approval
        ? { approval: { ...this.approval.req, id: this.approval.id, pending: rt.broker.pending } }
        : {}),
      ...(this.question
        ? {
            question: {
              id: this.question.id,
              agent: this.question.agent,
              question: this.question.q.question,
              ...(this.question.q.options ? { options: this.question.q.options } : {}),
            },
          }
        : {}),
      warnings: rt.warnings,
    };
  }

  addClient(res: ServerResponse): Client {
    const c: Client = { res, lastItemId: 0, first: true };
    this.clients.add(c);
    this.send(c);
    return c;
  }

  private send(c: Client): void {
    try {
      c.res.write(`event: state\ndata: ${JSON.stringify(this.build(c))}\n\n`);
      c.first = false;
    } catch {
      this.clients.delete(c);
    }
  }

  push(immediate = false): void {
    if (this.disposed || !this.clients.size) return;
    if (immediate) {
      if (this.timer) clearTimeout(this.timer);
      this.timer = undefined;
      for (const c of [...this.clients]) this.send(c);
      return;
    }
    this.timer ??= setTimeout(() => {
      this.timer = undefined;
      for (const c of [...this.clients]) this.send(c);
    }, 33);
  }

  heartbeat(): void {
    for (const c of [...this.clients]) {
      try {
        c.res.write(': hb\n\n');
      } catch {
        this.clients.delete(c);
      }
    }
  }

  // ---- commands ---------------------------------------------------------------------------------------

  prompt(text: string): void {
    const rt = this.runtime;
    if (!text.trim()) throw new HttpError(400, 'Empty message');
    if (rt.swarm) {
      const m = /^@([a-z][a-z0-9_-]*)\s+([\s\S]*)$/i.exec(text);
      rt.swarm.say(m ? m[2]! : text, m?.[1]?.toLowerCase());
      return;
    }
    this.store.user(text);
    if (rt.agent.isRunning) rt.agent.steer(text);
    else void rt.agent.run(text);
  }

  abort(): void {
    this.runtime.agent.abort();
    this.runtime.swarm?.abortAll();
  }

  answerApproval(id: number, r: ApprovalResponse): void {
    if (this.approval?.id !== id) throw new HttpError(409, 'That approval is no longer pending');
    this.approval.resolve(r);
  }

  answerQuestion(id: number, text: string): void {
    if (this.question?.id !== id) throw new HttpError(409, 'That question is no longer pending');
    this.question.resolve(text);
  }

  async settings(body: { mode?: unknown; sandbox?: unknown; model?: unknown }): Promise<void> {
    const rt = this.runtime;
    if (body.mode !== undefined) {
      if (!['ask', 'edits', 'auto', 'plan'].includes(String(body.mode)))
        throw new HttpError(400, 'Invalid mode');
      rt.setApprovalMode(body.mode as ApprovalMode);
    }
    if (body.sandbox !== undefined) {
      if (!['off', 'guard', 'container'].includes(String(body.sandbox)))
        throw new HttpError(400, 'Invalid sandbox');
      try {
        rt.setSandboxMode(body.sandbox as SandboxMode);
      } catch (e) {
        throw new HttpError(400, (e as Error).message);
      }
    }
    if (body.model !== undefined) {
      try {
        await rt.setModel(String(body.model));
      } catch (e) {
        throw new HttpError(400, (e as Error).message);
      }
    }
    this.push(true);
  }

  async compact(instructions?: string): Promise<boolean> {
    const ok = await this.runtime.agent.compactNow(undefined, instructions);
    this.push(true);
    return ok;
  }

  async swarm(action: string, arg?: string): Promise<void> {
    const rt = this.runtime;
    try {
      if (action === 'stop') {
        rt.stopSwarm();
        this.store.detachSwarm();
      } else if (action === 'start' || action === 'resume') {
        if (!arg) throw new HttpError(400, action === 'start' ? 'Which preset?' : 'Which swarm?');
        const sw = action === 'start' ? await rt.startSwarm(arg) : await rt.resumeSwarm(arg);
        this.store.attachSwarm(sw);
      } else throw new HttpError(400, 'Unknown swarm action');
    } catch (e) {
      if (e instanceof HttpError) throw e;
      throw new HttpError(400, (e as Error).message);
    }
    this.push(true);
  }

  async browser(action: string): Promise<void> {
    const b = this.runtime.browser;
    if (!b) throw new HttpError(400, 'Browser control is disabled');
    if (action === 'takeover') b.setControl('user');
    else if (action === 'release') b.setControl('agent');
    else if (action === 'close') await b.close();
    else throw new HttpError(400, 'Unknown browser action');
    this.push(true);
  }

  newConversation(): void {
    if (this.runtime.agent.isRunning) throw new HttpError(409, 'Interrupt the current turn first');
    this.runtime.newSession();
    this.store.clear();
    this.push(true);
  }

  async dispose(): Promise<void> {
    this.disposed = true;
    if (this.timer) clearTimeout(this.timer);
    for (const c of this.clients) {
      try {
        c.res.end();
      } catch {
        /* already closed */
      }
    }
    this.clients.clear();
    this.store.dispose();
    this.approval?.resolve({ allow: false });
    this.question?.resolve('(session closed)');
    await this.runtime.dispose();
  }

  get summary() {
    return {
      id: this.id,
      cwd: this.runtime.cwd,
      model: this.runtime.modelSpec ?? null,
      mode: this.runtime.policy.mode,
      running: this.runtime.agent.isRunning,
      swarm: !!this.runtime.swarm,
      createdAt: this.createdAt,
      clients: this.clients.size,
    };
  }
}

export class SessionManager {
  private sessions = new Map<string, WebSession>();

  constructor(
    readonly roots: string[],
    private opts: { maxSessions: number; headless: boolean; env: NodeJS.ProcessEnv },
  ) {}

  /** A workspace must be an existing directory inside one of the configured roots (symlinks resolved). */
  resolveWorkspace(cwd: unknown): string {
    if (typeof cwd !== 'string' || !cwd) throw new HttpError(400, 'cwd is required');
    let real: string;
    try {
      real = realpathSync(resolve(cwd));
      if (!statSync(real).isDirectory()) throw new Error('not a directory');
    } catch {
      throw new HttpError(400, `Not a directory: ${cwd}`);
    }
    if (!this.roots.some((r) => isInside(real, r))) {
      throw new HttpError(403, 'That folder is outside the directories this server is allowed to work in.');
    }
    return real;
  }

  async create(body: CreateSessionBody): Promise<WebSession> {
    if (this.sessions.size >= this.opts.maxSessions) {
      throw new HttpError(
        429,
        `At most ${this.opts.maxSessions} sessions can be open at once. Close one first.`,
      );
    }
    const cwd = this.resolveWorkspace(body.cwd);
    try {
      const s = await WebSession.create(body, this.opts.env, { cwd, headless: this.opts.headless });
      this.sessions.set(s.id, s);
      return s;
    } catch (e) {
      if (e instanceof HttpError) throw e;
      throw new HttpError(400, (e as Error).message);
    }
  }

  get(id: string): WebSession {
    const s = this.sessions.get(id);
    if (!s) throw new HttpError(404, 'No such session');
    return s;
  }

  list() {
    return [...this.sessions.values()].map((s) => s.summary);
  }

  /** Earlier sessions and swarms saved for a folder, for the "resume" picker. */
  saved(cwd: unknown) {
    const dir = this.resolveWorkspace(cwd);
    const paths = appPaths(this.opts.env);
    return {
      // Only ids and previews leave the server, never file-system paths.
      sessions: Session.list(sessionDir(paths.data, projectKey(dir)))
        .slice(0, 30)
        .map((x) => ({ id: x.id, preview: x.preview, updated: x.updated })),
      swarms: SwarmStore.list(join(paths.data, 'swarms', projectKey(dir)))
        .slice(0, 30)
        .map((x) => ({
          id: x.id,
          name: x.name,
          agents: x.agents,
          updated: x.updatedAt,
          messages: x.messages,
        })),
    };
  }

  async close(id: string): Promise<void> {
    const s = this.get(id);
    this.sessions.delete(id);
    await s.dispose();
  }

  heartbeat(): void {
    for (const s of this.sessions.values()) s.heartbeat();
  }

  async disposeAll(): Promise<void> {
    await Promise.allSettled([...this.sessions.values()].map((s) => s.dispose()));
    this.sessions.clear();
  }
}
